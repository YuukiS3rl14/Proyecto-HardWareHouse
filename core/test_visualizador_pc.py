from pathlib import Path

from django.test import TestCase
from django.urls import reverse


class VisualizadorPcTests(TestCase):
    def test_el_armador_incluye_el_visualizador_sin_cambiar_el_resumen(self):
        pagina = self.client.get(reverse('core:armado'))

        self.assertEqual(pagina.status_code, 200)
        self.assertContains(pagina, 'Vista 3D de tu PC')
        self.assertContains(
            pagina,
            'Representación 3D referencial. La apariencia y las dimensiones pueden diferir de los productos reales.',
        )
        self.assertContains(pagina, '0 de 8 categorías')
        self.assertContains(pagina, 'No se pudo iniciar la vista 3D. El armador sigue disponible.')
        self.assertContains(pagina, 'three.module.js')
        self.assertContains(pagina, 'pc-visualizer.js?v=vista98')
        self.assertContains(pagina, 'id="pc-visualizador-bahias"')
        self.assertContains(pagina, 'id="pc-visualizador-inspeccion"')
        self.assertContains(pagina, 'id="pc-visualizador-carga"')
        self.assertContains(pagina, 'class="armado-seleccion"')
        self.assertContains(pagina, 'class="armado-lateral"')
        self.assertContains(pagina, 'aria-label="Restablecer cámara"')
        self.assertContains(pagina, 'aria-label="Acercar"')
        self.assertContains(pagina, 'aria-label="Alejar"')
        self.assertContains(pagina, 'id="recomendar-pc-btn"')
        self.assertContains(pagina, 'Arma tu PC con IA')
        self.assertContains(pagina, 'Recomiéndame un PC')
        self.assertContains(pagina, 'id="add-to-cart-btn"')
        self.assertContains(pagina, 'id="download-excel-btn"')
        self.assertContains(pagina, 'id="limpiar-armado-btn"')
        self.assertContains(pagina, 'Descargar Excel')
        self.assertContains(pagina, 'id="resumen-presupuesto"')
        self.assertContains(pagina, 'pc-visualizer.css?v=vista15')
        html_footer = pagina.content.decode().split('id="resumen-presupuesto"', 1)[1].split('builder-mobile-bar', 1)[0]
        self.assertLess(html_footer.index('id="add-to-cart-btn"'), html_footer.index('id="download-excel-btn"'))
        self.assertLess(html_footer.index('id="download-excel-btn"'), html_footer.index('id="limpiar-armado-btn"'))
        html = pagina.content.decode()
        marca_columnas = html.find('class="armado-columnas')
        inicio_columnas = html.rfind('<div', 0, marca_columnas)
        fin_columnas = html.find('</div>\n</div>\n\n{{ componentes|json_script', inicio_columnas)
        if fin_columnas < 0:
            fin_columnas = html.find('id="builder-urls"', inicio_columnas)
        columnas = html[inicio_columnas:fin_columnas]
        self.assertIn('id="resumen-presupuesto"', columnas)
        self.assertIn('id="pc-visualizador"', columnas)
        self.assertIn('id="pc-builder"', columnas)
        self.assertEqual(columnas.count('<div'), columnas.count('</div>'))

